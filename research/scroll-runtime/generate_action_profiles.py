"""Generate immutable action bridge recipes from the existing audited emitter.

Reads pinned executables only. Does not load, execute, or patch a game.
"""
import hashlib
import json
from pathlib import Path
import struct

from action_detours import audited_sites, emit, unwind_segments
from action_loader import bundle
from local_paths import resolve

HERE = Path(__file__).resolve().parent
RUNTIME = 0x1122334455667788
CALLBACK = 0x2233445566778899
BASE = 0x150000000


def sources():
    return json.loads((HERE / "binder-profiles.json").read_text())


def profile(source):
    """One game version's recipe; needs only that version's pinned executable."""
    symbols = Path("C:/tmp/scroll-hook-research-20261009/EEex/EEex/loader") / ("v" + source["version"]) / "bg2ee/function_names.db"
    pe, sites = audited_sites(resolve(source["source"]), symbols)
    plans, records = [], []
    for index, site in enumerate(sites):
        plan = emit(site, image_base=pe.OPTIONAL_HEADER.ImageBase,
                    stub=BASE + index * 0x400, runtime=RUNTIME,
                    callback=CALLBACK, observed=site.body)
        code = plan["code"]
        assert len(code) < 0x400
        relocations = {}
        for name, value in (("runtime", RUNTIME), ("callback", CALLBACK)):
            raw = struct.pack("<Q", value)
            assert code.count(raw) == 1
            relocations[name] = code.index(raw)
        assert code[-19:-16] == b"\xc7\x04\x24"
        assert code[-12:-8] == b"\xc7\x44\x24\x04"
        assert code[-4:] == b"\xff\x64\x24\x00"
        relocations.update(resume_lo=len(code)-16, resume_hi=len(code)-8)
        records.append(dict(operation=site.operation,
                            function=site.function-pe.OPTIONAL_HEADER.ImageBase,
                            body_size=len(site.body), sha256=hashlib.sha256(site.body).hexdigest(),
                            site=site.address-pe.OPTIONAL_HEADER.ImageBase,
                            original=site.original.hex(), code_offset=index*0x400,
                            code_size=len(code), **relocations))
        plans.append((plan, unwind_segments(pe, site, plan)))
    packaged = bundle(BASE, plans)
    return dict(version=source["version"], timestamp=source["timestamp"],
                image_size=source["image_size"], sites=records,
                payload=packaged.payload.hex(), table_offset=packaged.table_offset,
                count=packaged.count)


def generate():
    return [profile(source) for source in sources()]


def header(profiles):
    def byte_values(value):
        return ",".join(f"0x{b:02x}" for b in value)
    lines = ["// Generated by generate_action_profiles.py; do not hand-edit.", "#pragma once", "#include <cstdint>",
             "namespace cbm::scroll::actions {",
             "struct Site {uint32_t function,body_size,site,patch_size,code_offset,code_size,runtime,callback,resume_lo,resume_hi; unsigned char sha[32],original[8];};",
             "struct Profile {const char* version; uint32_t timestamp,image_size,payload_size,table_offset,count; const unsigned char* payload; Site sites[3];};"]
    for i, p in enumerate(profiles):
        payload = bytes.fromhex(p["payload"])
        lines.append(f"inline constexpr unsigned char payload_{i}[]={{")
        lines.extend(byte_values(payload[start:start+32])+"," for start in range(0,len(payload),32))
        lines.append("};")
    lines.append("inline constexpr Profile profiles[]={")
    for i, p in enumerate(profiles):
        lines.append('{"%s",%du,%du,sizeof(payload_%d),%du,%du,payload_%d,{' %
                     (p["version"],p["timestamp"],p["image_size"],i,p["table_offset"],p["count"],i))
        for s in p["sites"]:
            values = [s[k] for k in ("function","body_size","site")]+[len(bytes.fromhex(s["original"]))]+[s[k] for k in ("code_offset","code_size","runtime","callback","resume_lo","resume_hi")]
            lines.append("{"+",".join(str(v)+"u" for v in values)+",{"+byte_values(bytes.fromhex(s["sha256"]))+"},{"+byte_values(bytes.fromhex(s["original"]))+"}},")
        lines.append("}},")
    lines.extend(["};", "}", ""])
    return "\n".join(lines)


if __name__ == "__main__":
    result = generate()
    (HERE / "action-profiles.json").write_text(json.dumps(result,indent=2)+"\n")
    (HERE / "action_profiles.hpp").write_text(header(result))
    for p in result:
        print(p["version"], "bytes", len(bytes.fromhex(p["payload"])), "unwind ranges", p["count"])
