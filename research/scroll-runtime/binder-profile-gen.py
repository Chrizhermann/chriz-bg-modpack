"""Generate audited instruction hashes from read-only pinned local executables.

This does not load/launch the engine. Full symbol spans include internal jump
tables and padding; generation refuses spans containing PE base relocations.
"""
import os

from local_paths import recorded
import hashlib
import json
from pathlib import Path

import pefile

HERE = Path(__file__).resolve().parent
SYMBOLS = Path("C:/tmp/scroll-hook-research-20261009/EEex/EEex/loader")
INPUTS = [
    # Local game folders: set BG2EE_266_ROOT and BG2EE_273_ROOT.
    ("2.6.6.0", Path(os.path.expandvars("%BG2EE_266_ROOT%/Baldur.exe")),
     "fc821a4806a0305b84fd85f1aad2bd472c8db642ed34b4494ae62351cae1c580"),
    ("2.7.3.0", Path(os.path.expandvars("%BG2EE_273_ROOT%/Baldur.exe")),
     "b51093a49140b2b8a7c046b4652bb8e535be24ebbc12b1d735e0b94217a14d57"),
]
# First eight are the exact exported function-table order.
FUNCTIONS = [
    "CGameObjectArray::GetDeny", "CAIObjectType::GetActiveInactiveClasses",
    "CDerivedStats::GetLevel", "CDerivedStats::GetMaximumLevel",
    "CScreenWizSpell::CanCastMageSpells", "CScreenPriestSpell::CanCastPriestSpells",
    "CSpell::GetCasterType", "CGameSprite::GetCasterLevel",
    "CAIObjectType::IsUsableSubClass", "CDerivedStats::GetLevelField",
    "CGameSprite::GetKitMask", "CGameAnimationType::GetMoveScale",
    "CDerivedStats::GetPriestLevelCast", "CDerivedStats::GetWizardLevelCast",
    "CSpell::GetLevel", "CGameSprite::GetMinCasterLevel",
    "CDerivedStats::GetAverageLevel", "max", "sscanf",
]


def main():
    profiles = []
    output = ["// Generated by binder-profile-gen.py; reviewed source pins in binder-profiles.json.",
              "#pragma once", "namespace cbm::scroll::binding {",
              "struct Signature { const char* name; unsigned rva, size; unsigned char sha[32]; };",
              "struct Profile { const char* version; unsigned timestamp, image_size, entry;",
              "    const Signature* signatures; std::size_t count; };" ]
    for index, (version, path, digest) in enumerate(INPUTS):
        raw = path.read_bytes()
        assert hashlib.sha256(raw).hexdigest() == digest, "unreviewed executable"
        pe = pefile.PE(data=raw)
        assert pe.FILE_HEADER.Machine == 0x8664 and pe.OPTIONAL_HEADER.Magic == 0x20B
        records = [line.partition("\t") for line in (SYMBOLS / f"v{version}/bg2ee/function_names.db").read_text().splitlines()]
        names = {name: int(address, 16) for address, _, name in records if address.startswith("0x")}
        addresses = sorted(set(names.values()))
        relocations = [entry.rva for block in getattr(pe, "DIRECTORY_ENTRY_BASERELOC", []) for entry in block.entries if entry.type]
        assert hasattr(pe, "DIRECTORY_ENTRY_BASERELOC") or pe.OPTIONAL_HEADER.DATA_DIRECTORY[5].Size == 0
        profile = {"version": version, "source": recorded(path), "sha256": digest,
                   "timestamp": pe.FILE_HEADER.TimeDateStamp, "image_size": pe.OPTIONAL_HEADER.SizeOfImage,
                   "entry": pe.OPTIONAL_HEADER.AddressOfEntryPoint, "preferred_base": pe.OPTIONAL_HEADER.ImageBase,
                   "signatures": []}
        output.append(f"inline constexpr Signature signatures_{index}[] = {{")
        for name in FUNCTIONS:
            address = names[name]
            end = addresses[addresses.index(address) + 1]
            rva, size = address - pe.OPTIONAL_HEADER.ImageBase, end - address
            assert 0 < size < 0x4000
            assert not any(rva - 7 <= relocation < rva + size for relocation in relocations), (name, "relocation requires audit")
            code = pe.get_data(rva, size)
            assert len(code) == size
            signature = hashlib.sha256(code).hexdigest()
            profile["signatures"].append({"name": name, "rva": rva, "size": size, "sha256": signature})
            byte_list = ",".join("0x" + signature[n:n+2] for n in range(0, 64, 2))
            output.append(f'    {{"{name}", 0x{rva:X}, 0x{size:X}, {{{byte_list}}}}},')
        output.append("};")
        profiles.append(profile)
    output.append("inline constexpr Profile profiles[] = {")
    for index, profile in enumerate(profiles):
        output.append(f'    {{"{profile["version"]}", 0x{profile["timestamp"]:X}, 0x{profile["image_size"]:X}, 0x{profile["entry"]:X}, signatures_{index}, std::size(signatures_{index})}},')
    output.extend(["};", "} // namespace cbm::scroll::binding", ""])
    (HERE / "binder_profiles.hpp").write_text("\n".join(output), encoding="utf-8")
    (HERE / "binder-profiles.json").write_text(json.dumps(profiles, indent=2) + "\n", encoding="utf-8")
    print("Generated", len(profiles), "profiles with", len(FUNCTIONS), "complete instruction spans each")


if __name__ == "__main__":
    main()
