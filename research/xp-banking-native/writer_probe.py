"""Read-only native stat44 extraction and relocation/Windows-unwind fixtures.

Extracts one reviewed function (1936 bytes), its8-byte unwind recipe and precise
branch metadata. No game is launched; native harness uses synthetic actors.
"""
import hashlib,json
from pathlib import Path
import capstone,pefile
from identity_probe import DEFAULT_EXES,DEFAULT_CACHE
from award_probe import lua_literal

ROOT=Path(__file__).resolve().parent
MD=capstone.Cs(capstone.CS_ARCH_X86,capstone.CS_MODE_64);MD.detail=True
XP=bytes.fromhex('4183f901750c44018170050000e9bd00000044898170050000e9b1000000')

def main():
    profiles={};results=[];lines=['// Generated pinned function windows; never a full engine image.']
    for version,path in DEFAULT_EXES.items():
        full=version+('.6.0' if version=='2.6' else '.3.0')
        names=(DEFAULT_CACHE/('v'+full)/'bg2ee/function_names.db').read_text()
        address=int(next(l.split('\t')[0] for l in names.splitlines() if l.endswith('\tCGameSprite::SetAtOffset')),16)
        raw=path.read_bytes();pe=pefile.PE(data=raw);rva=address-pe.OPTIONAL_HEADER.ImageBase
        body=bytes(pe.get_data(rva,0x790));assert body.count(XP)==1
        branch=body.index(XP);assert branch==0x577
        assert body[:4]==bytes.fromhex('4883ec28')
        entry=next(x.struct for x in pe.DIRECTORY_ENTRY_EXCEPTION if x.struct.BeginAddress==rva)
        unwind=bytes(pe.get_data(entry.UnwindData,8));assert unwind==bytes.fromhex('0104010004420000')
        tail=0x646;calls=[];fixups=[]
        for ins in MD.disasm(body[:0x672],rva):
            if ins.mnemonic=='call':calls.append(ins.address-rva)
            for op in ins.operands:
                if op.type==capstone.CS_OP_MEM and op.mem.base==capstone.x86_const.X86_REG_RIP:
                    if ins.mnemonic=='movzx':fixups.append((ins.address-rva,ins.size,ins.disp_offset))
        assert calls==[0x655] and len(fixups)==2
        table=0x674;assert int.from_bytes(body[table+43*4:table+44*4],'little')==rva+branch
        profiles[version]={'gameTimestamp':pe.FILE_HEADER.TimeDateStamp,'gameSize':pe.OPTIONAL_HEADER.SizeOfImage,
            'rva':rva,'entryBytes':body[:0x25].hex(),'branch':branch,'branchBytes':XP.hex(),
            'tail':tail,'tailBytes':body[tail:0x672].hex(),'tableXP':table+43*4}
        suffix=version.replace('.','_')
        lines.append('static const unsigned char writer_body_'+suffix+'[]={'+','.join('0x%02x'%n for n in body)+'};')
        lines.append('static const unsigned char writer_unwind_'+suffix+'[]={'+','.join('0x%02x'%n for n in unwind)+'};')
        lines.append('static const unsigned writer_end_'+suffix+'='+str(entry.EndAddress-rva)+';')
        results.append({'version':version,'functionRva':hex(rva),'branchRva':hex(rva+branch),
            'tailRva':hex(rva+tail),'unwindBytes':unwind.hex(),'bodySha256':hashlib.sha256(body).hexdigest(),
            'callsBeforeTail':0,'callsInTail':1,'returnConstantFixups':fixups,'gameLaunched':False})
    (ROOT/'writer_profiles.lua').write_text('-- Generated by writer_probe.py.\nreturn '+lua_literal(profiles)+'\n')
    (ROOT/'writer_native_windows.inc').write_text('\n'.join(lines)+'\n')
    (ROOT/'writer-check-results.json').write_text(json.dumps(results,indent=2)+'\n')
    print(json.dumps(results,indent=2))

if __name__=='__main__':main()
