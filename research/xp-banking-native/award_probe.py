"""Extract only the audited224-byte leaf and validate both pinned builds.

No game is launched. The generated byte array is executed only by an offline
Windows harness against synthetic effect/actor buffers; it contains no calls,
external branches or RIP-relative references. Never copy a full game image.
"""
import hashlib
import json
from pathlib import Path

import capstone
import pefile

from identity_probe import DEFAULT_EXES
from check_probe import ENTRY,FUNC_HASH,native_case

ROOT=Path(__file__).resolve().parent


def lua_literal(value):
    if isinstance(value,dict):return '{'+','.join('['+json.dumps(k)+']='+lua_literal(v) for k,v in value.items())+'}'
    return json.dumps(value)


def main():
    profiles={};evidence=[];shared=None
    for version,path in DEFAULT_EXES.items():
        raw=path.read_bytes();pe=pefile.PE(data=raw)
        assert raw.count(ENTRY)==1
        rva=pe.get_rva_from_offset(raw.index(ENTRY));body=bytes(pe.get_data(rva,0xe0))
        assert hashlib.sha256(body).hexdigest()==FUNC_HASH
        if shared is not None:assert shared==body
        shared=body
        md=capstone.Cs(capstone.CS_ARCH_X86,capstone.CS_MODE_64);md.detail=True
        instructions=list(md.disasm(body,rva))
        for ins in instructions:
            assert ins.mnemonic!='call',ins
            for op in ins.operands:
                if op.type==capstone.CS_OP_MEM:assert op.mem.base!=capstone.x86_const.X86_REG_RIP
            if ins.group(capstone.CS_GRP_JUMP):
                assert ins.operands[0].type==capstone.CS_OP_IMM
                assert rva<=ins.operands[0].imm<rva+len(body)
        cases=0
        for before in (0,160999,499999,0x7fffffff,0xfffffffe,0xffffffff):
            for amount in (1,2,17,0x7fffffff):
                applied=min(amount,0xffffffff-before)
                result=native_case(body,before,applied)
                assert result['base']==before+applied and result['return']==1 and result['done']==result['force_repass']==1
                assert result['derived']==4321 and result['bonus']==1234
                assert before+amount==result['base']+(amount-applied)
                cases+=1
        profiles[version]={'gameTimestamp':pe.FILE_HEADER.TimeDateStamp,'gameSize':pe.OPTIONAL_HEADER.SizeOfImage,
            'rva':rva,'span':9,'bytes':body.hex()}
        evidence.append({'version':version,'exeSha256':hashlib.sha256(raw).hexdigest(),
            'rva':hex(rva),'bodySha256':FUNC_HASH,'cases':cases,'noCallsOrExternalBranches':True})
    (ROOT/'award_profiles.lua').write_text('-- Generated by award_probe.py from the two pinned PEs.\nreturn '+lua_literal(profiles)+'\n')
    values=','.join('0x%02x'%b for b in shared)
    (ROOT/'award_native_leaf.inc').write_text('// Audited identical native224-byte leaf; synthetic-buffer execution only.\nstatic const unsigned char native_leaf[]={'+values+'};\n')
    (ROOT/'award-check-results.json').write_text(json.dumps(evidence,indent=2)+'\n')
    print(json.dumps({'native_leaf_emulations':sum(e['cases'] for e in evidence),'game_launched':False}))

if __name__=='__main__':main()
